        long t8 = System.nanoTime();
        BookPage page54 = pages.get(53);
        RawToc rawToc = extractTocFromPageContent(page54.getMarkdownContent());
        long t9 = System.nanoTime();
        double tocExtractMs = (t9 - t8) / 1_000_000.0;
        assertEquals(11, rawToc.entries().size());

        // 6. Windowed Monotonic TOC Alignment
        long t10 = System.nanoTime();
        List<TocAligner.AlignedSection> aligned = tocAligner.align(rawToc, pages, resolver, mode);
        long t11 = System.nanoTime();
        double alignMs = (t11 - t10) / 1_000_000.0;
        assertEquals(11, aligned.size());
        for (TocAligner.AlignedSection s : aligned) {
            System.out.printf("TOC SECTION: %s | page: %d | anchor: %s | conf: %s | needsReview: %s%n",
                    s.title(), s.startPage(), s.startAnchor(), s.confidence(), s.needsReview());
        }

        // 7. Section Tree Builder
        long t12 = System.nanoTime();
        Book book = new Book();
        book.setId(42L);
