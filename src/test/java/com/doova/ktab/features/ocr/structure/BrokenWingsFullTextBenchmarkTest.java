    private RawToc extractTocFromPageContent(String pageContent) {
        List<RawToc.RawTocEntry> entries = new ArrayList<>();
        String[] lines = pageContent.split("\\r?\\n");
        for (String line : lines) {
            String trimmed = line.trim();
            if (trimmed.contains("...") || trimmed.contains(". .") || trimmed.matches(".*\\d+\\s*\\.{3,}.*")) {
                String[] parts = trimmed.split("\\.{3,}");
                if (parts.length >= 2) {
                    String pagePart = parts[0].trim();
                    String titlePart = parts[1].replaceAll("^[-\\s]+|[-\\s]+$", "").trim();
                    if (!pagePart.isBlank() && !titlePart.isBlank() && Character.isDigit(pagePart.charAt(0))) {
                        entries.add(new RawToc.RawTocEntry(
                                titlePart,
                                null,
                                null,
                                1,
                                pagePart,
                                SectionType.CHAPTER
                        ));
                    }
                }
            }
        }
        return new RawToc(entries);
    }

    private List<BookPage> loadAll54Pages() {
        List<BookPage> pages = new ArrayList<>();
        String[] texts = RAW_PAGES;
        for (int i = 0; i < texts.length; i++) {
            BookPage p = new BookPage();
            p.setPageNumber(i + 1);
            p.setSourcePdfPage(i + 1);
            p.setPrintedPageLabel(String.valueOf(i + 1));
            p.setMarkdownContent(texts[i]);
            pages.add(p);
        }
        return pages;
    }

