package com.doova.ktab.features.ai.prompt;

public class EndingGeneratorPrompt {

    public static String build(int wordCount, String audience) {

        return """
                اقرأ الملف المرفق (PDF أو Word) قراءة دقيقة وعميقة، ثم أنشئ "خاتمة كتاب" \s
                باللغة الأصلية للملف، وبالطول المطلوب: %d كلمة (بهامش ±15٪)، \s
                وتناسب تماماً خصائص واحتياجات الفئة المستهدفة: %s، \s
                وتُكتب بأسلوب المؤلف نفسه، وكأنها جزء أصيل من الكتاب.
               \s
                ---
               \s
                ## 🚫 قواعد الإهمال الإلزامية
               \s
                ❗ إذا احتوى الكتاب على صور، يجب تجاهلها تماماً وعدم اعتمادها في التحليل أو التوليد.
                النص فقط هو المرجع الوحيد المعتمد.
               \s
                ---
               \s
                     ###  تحديد اللغة
                     - حلل النص المرفق لتحديد لغته الأصلية بدقة
                     - اللغة المكتشفة = لغة الخاتمة (بدون استثناء)
                    \s
                     ###  تطابق اللغة
                     - إذا كان الكتاب عربي ← الخاتمة بالعربية الفصحى أو اللهجة حسب النص
                     - إذا كان الكتاب إنجليزي ← الخاتمة بالإنجليزية
                     - إذا كان الكتاب فرنسي ← الخاتمة بالفرنسية
                     - **ممنوع تغيير اللغة تحت أي ظرف**
                    \s
                     ---
               \s
                ────────────────────────────────────────
                ### 🔹 المرحلة الأولى — المعالجة الداخلية (لا تُعرض للمستخدم)
                ────────────────────────────────────────
               \s
                قبل توليد الخاتمة يجب على النموذج إنشاء نسخة داخلية “مصحّحة بالكامل” من النص الأصلي.
                هذه النسخة هي المرجع الوحيد المسموح الاعتماد عليه في فهم الكتاب.
                يُمنع منعاً باتاً استخدام النص الخام كما هو.
               \s
                #### ✦ يجب إصلاح كل التشوهات:
               \s
                * تكسّر الكلمات أو تقسيمها
                * المسافات أو الرموز العشوائية داخل الكلمات
                * الأخطاء الناتجة عن OCR
                * الجمل أو الفقرات المقطوعة
                * الفقرات المدمجة بلا منطق
                * الترقيم المختل أو المفقود
                * الحواشي والهوامش التي اندمجت داخل النص
                * أي مقطع تالف بالكامل يُهمل
               \s
                #### ✦ قواعد إلزامية:
               \s
                * النسخة المصححة داخلية فقط.
                * دمج الكلمات المنقسمة.
                * استكمال أي جملة ناقصة بشكل منطقي.
                * يُمنع الاقتباس الحرفي من النص الأصلي.
                * تُهمل جميع الصور، الرسوم، أو الجداول إن وُجدت.
               \s
                ────────────────────────────────────────
                ### 🔹 المرحلة الثانية — الفهم العميق وتحليل بنية الكتاب
                ────────────────────────────────────────
               \s
                اعتماداً على النسخة المصحّحة، يجب تحليل:
               \s
                1) **نوع الكتاب:**
                   * رواية – قصة – سيرة – كتاب رأي – كتاب علمي – تربوي – معرفي – فلسفي…
               \s
                2) **العناصر السردية (إن كان أدبياً):**
                   * الشخصيات الأساسية
                   * الصراع المحوري
                   * الثيمة العامة
                   * مسار الأحداث
                   * اللحظات العاطفية
                   * الإيقاع والأسلوب (وصفي، تأملي، حواري…)
               \s
                3) **العناصر الفكرية (إن كان غير أدبي):**
                   * الموضوع المركزي
                   * السؤال الذي يطرحه المؤلف
                   * زاوية المعالجة
                   * الحركة الفكرية من بداية النص حتى نهايته
                   * ما يحتاج إغلاقاً أو تلخيصاً عميقاً
               \s
                4) **نبرة الكتاب:**
                   * شعرية، سردية، علمية، تأملية، فلسفية، تربوية، تحليلية…
               \s
                5) **خصائص الفئة المستهدفة (%s) ومتطلباتها:**
                   * ✦ يجب تحديد خصائص الفئة بدقة (السن، مستوى التعليم، الاهتمامات، الخلفية الثقافية…).
                   * ✦ يجب مواءمة اللغة والمفاهيم والسياق مع مستوى الفهم والمعرفة لدى الفئة.
               \s
                #### ✦ أمثلة إرشادية حسب الفئة:
                * **أطفال** — لغة بسيطة، خيال واسع، نهايات دافئة، صور حسية
                * **مراهقون** — واقع قريب منهم، محفّز، حوارات صادقة
                * **جمهور عام** — لغة سلسة، أفكار واضحة، توازن بين العمق والبساطة
                * **أكاديميون** — منهجية، دقة، وضوح في الطرح الفكري
                * **معلّمون** — تطبيقات، أدوات تعليمية، سياقات صفّية
                * **تنفيذيون** — تركيز، نتائج، رؤية استراتيجية
                * **باحثون** — تحليل متماسك، ربط منطقي، عمق مفاهيمي
               \s
                * ✦ يجب أن تعكس الخاتمة توقعات الفئة من حيث الأسلوب والمحتوى والمغزى.
               \s
                ────────────────────────────────────────
                ### 🔹 المرحلة الثالثة — هندسة الخاتمة (Stage of Reasoning)
                ────────────────────────────────────────
               \s
                قبل البدء بالكتابة، يجب على النموذج:
               \s
                1) **تحديد علاقتها** (سبب → تطور → معنى).
                2) **اختيار نوع الخاتمة الأنسب:**
                   * مغلقة – مفتوحة – رمزية – تأملية – تعليمية – علمية – سردية…
               \s
                3) **إعادة تبنّي “صوت المؤلف” بالكامل:**
                   * نفس الأسلوب
                   * نفس الإيقاع
                   * نفس النبرة
                   * نفس عمق الجمل
                   * نفس مزاج الكتاب
               \s
                #### ❗ قاعدة إلزامية للصوت:
                يجب أن تبدو الخاتمة وكأن **المؤلف نفسه كتبها**، وليس تعليقاً من الخارج.
               \s
                **يُمنع تماماً استخدام أي عبارات مثل:**
                * «يقول الكاتب…»
                * «في هذا الكتاب يناقش المؤلف…»
                * «يشير النص إلى…»
                * «يهدف الكاتب إلى…»
                * «يسعى المؤلف…»
               \s
                الخاتمة يجب أن تكون **داخل عالم الكتاب نفسه** — ليست نقداً ولا تلخيصاً ولا حديثاً عن المؤلف.
               \s
                ────────────────────────────────────────
                ### 🔹 المرحلة الرابعة — كتابة الخاتمة
                ─────────────────────────────────────────
               \s
                #### ✦ مواصفات الخاتمة:
               \s
                | المواصفة | القيمة المطلوبة |
                | :--- | :--- |
                | **اللغة** | نفس لغة الملف الأصلي |
                | **عدد الكلمات** | %d ±15٪ |
                | **الفئة المستهدفة** | %s |
                | **الأسلوب** | أسلوب المؤلف، دون خروج عنه |
                | **الدور** | المتكلم = المؤلف الحقيقي (الصوت الداخلي للكتاب) |
               \s
                #### ✦ قواعد الكتابة:
               \s
                * الخاتمة يجب أن تبدو كأنها آخر صفحة في الكتاب.
                * لا يُسمح بأي تعليق خارجي أو وصف للكتاب أو للمؤلف.
                * لا يجوز الإشارة للكتاب بصفته "نصاً" أو "عملاً".
                * لا يجب ذكر “أهداف الكتاب”، “رسالة الكاتب”، أو أي خطاب خارجي.
                * الخاتمة = جزء عضوي من النص، تُغلق المعنى أو تفتحه.
                * يُمنع النسخ الحرفي من النص الأصلي.
                * تُستخدم النسخة المصححة فقط كمصدر للفهم.
               \s
                > **ملاحظة الإجتزاء:**
                > إذا كان النص الأصلي ناقصاً بشدة، يذكر في السطر الأخير فقط:
                > «ملاحظة: النص الأصلي المستخرج كان مجتزأً/غير مكتمل.»
               \s
                ────────────────────────────────────────
                ## 🎯 الهدف النهائي
               \s
                * إنتاج خاتمة أصيلة
                * مكتوبة بنفس لغة وأسلوب المؤلف
                * وتتجاهل أي صور أو عناصر غير نصيّة
                * وتلائم الفئة المستهدفة
                * وتقدّم نهاية جمالية أو فكرية أو سردية
                * كما لو كانت الصفحة الأخيرة من الكتاب.
               \s
                                **ممنوعات صارمة:**
                                ❌ تغيير اللغة
                                ❌ خلط اللغات
                                ❌ استخدام مفردات من مستوى لغوي مختلف
                                ❌ تغيير اللهجة (إذا كان النص بلهجة معينة)
               \s""".formatted(wordCount, audience, audience, wordCount, audience);
    }

}
